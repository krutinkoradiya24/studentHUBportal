    $tc6Res = runTestRegistration($pdo, [
        'full_name'        => 'Another Person',
        'username'         => $dupUsername,
        'email'            => 'second_' . bin2hex(random_bytes(2)) . '@testsuite.local',
        'password'         => 'AnotherPass123!',
        'confirm_password' => 'AnotherPass123!'
    ]);

    $countWithUnameAfter = (int)$pdo->query("SELECT COUNT(*) FROM users WHERE username = '$dupUsername'")->fetchColumn();

    $tc6Passed = ($tc6Res['success'] === false)
        && ($tc6Res['message'] === 'Username is already taken.')
        && ($countWithUnameBefore === 1)
        && ($countWithUnameAfter === 1);

    $results[] = [
        'id'       => 6,
        'name'     => 'Duplicate Username Validation',
        'input'    => "Username: '$dupUsername' (Attempting re-registration with duplicate username)",
        'expected' => 'Username is already taken. (Original record preserved, count = 1)',
        'actual'   => "{$tc6Res['message']} (Existing username count preserved at: $countWithUnameAfter)",
        'status'   => $tc6Passed ? 'PASS' : 'FAIL',
        'details'  => 'Verified uniqueness check & MySQL UNIQUE constraint prevent duplicate username.'
    ];

    // -------------------------------------------------------------
    // Test Case 7: Password Hashing & Successful Database Insertion
    // -------------------------------------------------------------
    $plainPassword = 'MySecretPlainTextPassword#2026';
    $tc7Username   = 'test_hash_user_' . bin2hex(random_bytes(2));
    $tc7Email      = 'hash_' . bin2hex(random_bytes(2)) . '@testsuite.local';

    $tc7Res = runTestRegistration($pdo, [
        'full_name'        => 'Hash Verification User',
        'username'         => $tc7Username,
        'email'            => $tc7Email,
        'password'         => $plainPassword,
        'confirm_password' => $plainPassword
    ]);

    $fetchStmt = $pdo->prepare('SELECT password_hash FROM users WHERE username = :uname');
    $fetchStmt->execute([':uname' => $tc7Username]);
    $row = $fetchStmt->fetch();
    $storedHash = $row ? $row['password_hash'] : '';

    $isNotPlain      = ($storedHash !== '' && $storedHash !== $plainPassword);
    $isBcrypt        = (str_starts_with($storedHash, '$2y$') || str_starts_with($storedHash, '$2a$'));
    $verifiesCorrect = password_verify($plainPassword, $storedHash);
    $rejectsWrong    = !password_verify('WrongPassword999', $storedHash);

    $tc7Passed = ($tc7Res['success'] === true)
        && $isNotPlain
        && $isBcrypt
        && $verifiesCorrect
        && $rejectsWrong;

    $results[] = [
        'id'       => 7,
        'name'     => 'Password Hashing & Successful Database Insertion',
        'input'    => "Plain Password: '$plainPassword'\nStored in MySQL VARCHAR(255) column",
        'expected' => "Stored hash != plain text, bcrypt format ($2y$), password_verify() returns true",
        'actual'   => "Stored Hash: " . substr($storedHash, 0, 20) . "...\nDiffers from plain: " . ($isNotPlain ? 'YES' : 'NO') . "\npassword_verify(plain): " . ($verifiesCorrect ? 'TRUE' : 'FALSE') . "\npassword_verify(wrong): " . ($rejectsWrong ? 'REJECTED' : 'ACCEPTED'),
        'status'   => $tc7Passed ? 'PASS' : 'FAIL',
        'details'  => 'Verified password_hash() with PASSWORD_DEFAULT and constant-time password_verify().'
    ];

    cleanupTestRecords($pdo);
    return $results;
}


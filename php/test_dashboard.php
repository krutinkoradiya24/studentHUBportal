/**
 * Execute Registration Simulator for Test Verification
 */
function runTestRegistration(PDO $pdo, array $postData): array {
    $fullName        = trim($postData['full_name'] ?? '');
    $username        = trim($postData['username'] ?? '');
    $email           = trim($postData['email'] ?? '');
    $password        = $postData['password'] ?? '';
    $confirmPassword = $postData['confirm_password'] ?? '';

    $missing = [];
    if ($fullName === '')        $missing[] = 'Full Name';
    if ($username === '')        $missing[] = 'Username';
    if ($email === '')           $missing[] = 'Email Address';
    if ($password === '')        $missing[] = 'Password';
    if ($confirmPassword === '') $missing[] = 'Confirm Password';

    if (!empty($missing)) {
        return [
            'success'        => false,
            'status_code'    => 400,
            'message'        => 'Please fill in all required fields.',
            'missing_fields' => $missing
        ];
    }

    if (mb_strlen($fullName) < 2 || mb_strlen($fullName) > 100) {
        return [
            'success'     => false,
            'status_code' => 400,
            'message'     => 'Full Name must be between 2 and 100 characters.'
        ];
    }

    if (!preg_match('/^[a-zA-Z0-9_]{3,50}$/', $username)) {
        return [
            'success'     => false,
            'status_code' => 400,
            'message'     => 'Username must be between 3 and 50 alphanumeric characters (letters, numbers, underscores).'
        ];
    }

    if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
        return [
            'success'     => false,
            'status_code' => 400,
            'message'     => 'Please enter a valid email address.'
        ];
    }

    if ($password !== $confirmPassword) {
        return [
            'success'     => false,
            'status_code' => 400,
            'message'     => 'Passwords do not match.'
        ];
    }

    if (strlen($password) < 6) {
        return [
            'success'     => false,
            'status_code' => 400,
            'message'     => 'Password must be at least 6 characters long.'
        ];
    }

    try {
        $stmtEmail = $pdo->prepare('SELECT id FROM users WHERE email = :email LIMIT 1');
        $stmtEmail->execute([':email' => $email]);
        if ($stmtEmail->fetch()) {
            return [
                'success'     => false,
                'status_code' => 409,
                'message'     => 'Email address is already registered.'
            ];
        }

        $stmtUser = $pdo->prepare('SELECT id FROM users WHERE username = :username LIMIT 1');
        $stmtUser->execute([':username' => $username]);
        if ($stmtUser->fetch()) {
            return [
                'success'     => false,
                'status_code' => 409,
                'message'     => 'Username is already taken.'
            ];
        }

        $hashedPassword = password_hash($password, PASSWORD_DEFAULT);

        $insert = $pdo->prepare('
            INSERT INTO users (full_name, username, email, password_hash)
            VALUES (:full_name, :username, :email, :password_hash)
        ');
        $insert->execute([
            ':full_name'     => $fullName,
            ':username'      => $username,
            ':email'         => $email,
            ':password_hash' => $hashedPassword
        ]);

        return [
            'success'         => true,
            'status_code'     => 201,
            'message'         => 'Registration successful!',
            'user_id'         => (int)$pdo->lastInsertId(),
            'hashed_password' => $hashedPassword
        ];
    } catch (PDOException $e) {
        if ($e->getCode() == 23000 || str_contains($e->getMessage(), '1062')) {
            if (str_contains($e->getMessage(), 'email')) {
                return ['success' => false, 'status_code' => 409, 'message' => 'Email address is already registered.'];
            }
            return ['success' => false, 'status_code' => 409, 'message' => 'Username is already taken.'];
        }
        return ['success' => false, 'status_code' => 500, 'message' => 'Database error occurred.'];
    }
}

/**
 * Clean up isolated test records generated by testing
 */
function cleanupTestRecords(PDO $pdo): void {
    try {
        $stmt = $pdo->prepare("
            DELETE FROM users 
            WHERE username LIKE 'test_%' 
               OR email LIKE '%@testsuite.local' 
               OR email LIKE '%duplicate.test@%'
        ");
        $stmt->execute();
    } catch (PDOException $e) {
        log_app_error('Cleanup error in test suite: ' . $e->getMessage(), $e);
    }
}


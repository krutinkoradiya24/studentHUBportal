 * Execute all 7 test cases and collect assertions
 */
function executeAllTests(): array {
    $pdo = getDbConnection();
    cleanupTestRecords($pdo);
    $results = [];

    // -------------------------------------------------------------
    // Test Case 1: Successful User Registration
    // -------------------------------------------------------------
    $uid = bin2hex(random_bytes(3));
    $tc1Input = [
        'full_name'        => 'Test User 1',
        'username'         => 'test_user_valid_' . $uid,
        'email'            => 'valid_' . $uid . '@testsuite.local',
        'password'         => 'CorrectPassword123!',
        'confirm_password' => 'CorrectPassword123!'
    ];

    $tc1Res = runTestRegistration($pdo, $tc1Input);

    $checkStmt = $pdo->prepare('SELECT id, full_name, username, email, password_hash FROM users WHERE username = :uname');
    $checkStmt->execute([':uname' => $tc1Input['username']]);
    $insertedRow = $checkStmt->fetch();

    $tc1Passed = ($tc1Res['success'] === true)
        && ($tc1Res['message'] === 'Registration successful!')
        && ($insertedRow !== false)
        && ($insertedRow['email'] === $tc1Input['email']);

    $results[] = [
        'id'       => 1,
        'name'     => 'Successful User Registration',
        'input'    => "Name: {$tc1Input['full_name']}\nUser: {$tc1Input['username']}\nEmail: {$tc1Input['email']}\nPass: [VALID_SECURE]",
        'expected' => 'Registration successful! (Record exists in MySQL users table)',
        'actual'   => $tc1Res['message'] . ($insertedRow ? " (Verified MySQL User ID #{$insertedRow['id']})" : ' (Record missing)'),
        'status'   => $tc1Passed ? 'PASS' : 'FAIL',
        'details'  => 'Verified all required fields, email format, password matching, hashing, and database row insertion.'
    ];

    // -------------------------------------------------------------
    // Test Case 2: Empty-Field Validation
    // -------------------------------------------------------------
    $tc2Input = [
        'full_name'        => '',
        'username'         => '',
        'email'            => '',
        'password'         => '',
        'confirm_password' => ''
    ];

    $countBefore = (int)$pdo->query('SELECT COUNT(*) FROM users')->fetchColumn();
    $tc2Res = runTestRegistration($pdo, $tc2Input);
    $countAfter = (int)$pdo->query('SELECT COUNT(*) FROM users')->fetchColumn();

    $tc2Passed = ($tc2Res['success'] === false)
        && ($tc2Res['message'] === 'Please fill in all required fields.')
        && ($countBefore === $countAfter);

    $results[] = [
        'id'       => 2,
        'name'     => 'Empty-Field Validation',
        'input'    => "full_name: ''\nusername: ''\nemail: ''\npassword: ''\nconfirm_password: ''",
        'expected' => 'Please fill in all required fields. (0 rows inserted in database)',
        'actual'   => "{$tc2Res['message']} (Rows before: $countBefore, after: $countAfter)",
        'status'   => $tc2Passed ? 'PASS' : 'FAIL',
        'details'  => 'Verified that submission is rejected with 400 and no database row was inserted.'
    ];

    // -------------------------------------------------------------
    // Test Case 3: Invalid Email Validation
    // -------------------------------------------------------------
    $invalidEmails = ['invalid-email', 'user@', 'user.example.com'];
    $tc3Passed = true;
    $tc3Actuals = [];

    foreach ($invalidEmails as $badEmail) {
        $countB = (int)$pdo->query('SELECT COUNT(*) FROM users')->fetchColumn();
        $res = runTestRegistration($pdo, [
            'full_name'        => 'Email Tester',
            'username'         => 'test_bad_email_' . bin2hex(random_bytes(2)),
            'email'            => $badEmail,
            'password'         => 'Password123!',
            'confirm_password' => 'Password123!'
        ]);
        $countA = (int)$pdo->query('SELECT COUNT(*) FROM users')->fetchColumn();

        if ($res['message'] !== 'Please enter a valid email address.' || $countB !== $countA) {
            $tc3Passed = false;
        }
        $tc3Actuals[] = "[$badEmail]: {$res['message']}";
    }

    $results[] = [
        'id'       => 3,
        'name'     => 'Invalid Email Validation',
        'input'    => "Tested values:\n- invalid-email\n- user@\n- user.example.com",
        'expected' => 'Please enter a valid email address. (0 rows inserted in database)',
        'actual'   => implode("\n", $tc3Actuals),
        'status'   => $tc3Passed ? 'PASS' : 'FAIL',
        'details'  => 'Validated server-side with filter_var($email, FILTER_VALIDATE_EMAIL).'
    ];

    // -------------------------------------------------------------
    // Test Case 4: Password Mismatch Validation
    // -------------------------------------------------------------
    $countBefore = (int)$pdo->query('SELECT COUNT(*) FROM users')->fetchColumn();
    $tc4Res = runTestRegistration($pdo, [
        'full_name'        => 'Mismatch Tester',
        'username'         => 'test_mismatch_' . bin2hex(random_bytes(2)),
        'email'            => 'mismatch_' . bin2hex(random_bytes(2)) . '@testsuite.local',
        'password'         => 'PasswordAlpha123!',
        'confirm_password' => 'PasswordBeta456!'
    ]);
    $countAfter = (int)$pdo->query('SELECT COUNT(*) FROM users')->fetchColumn();

    $tc4Passed = ($tc4Res['success'] === false)
        && ($tc4Res['message'] === 'Passwords do not match.')
        && ($countBefore === $countAfter);

    $results[] = [
        'id'       => 4,
        'name'     => 'Password Mismatch Validation',
        'input'    => "Password: 'PasswordAlpha123!'\nConfirm : 'PasswordBeta456!'",
        'expected' => 'Passwords do not match. (0 rows inserted in database)',
        'actual'   => "{$tc4Res['message']} (Rows before: $countBefore, after: $countAfter)",
        'status'   => $tc4Passed ? 'PASS' : 'FAIL',
        'details'  => 'Verified comparing password and confirm_password fields rejects mismatch.'
    ];

    // -------------------------------------------------------------
    // Test Case 5: Duplicate Email Validation
    // -------------------------------------------------------------
    $dupEmail = 'duplicate.test@testsuite.local';
    runTestRegistration($pdo, [
        'full_name'        => 'Original Owner',
        'username'         => 'orig_user_' . bin2hex(random_bytes(2)),
        'email'            => $dupEmail,
        'password'         => 'FirstPassword123!',
        'confirm_password' => 'FirstPassword123!'
    ]);

    $countWithEmailBefore = (int)$pdo->query("SELECT COUNT(*) FROM users WHERE email = '$dupEmail'")->fetchColumn();

    $tc5Res = runTestRegistration($pdo, [
        'full_name'        => 'Second User',
        'username'         => 'second_user_' . bin2hex(random_bytes(2)),
        'email'            => $dupEmail,
        'password'         => 'SecondPassword123!',
        'confirm_password' => 'SecondPassword123!'
    ]);

    $countWithEmailAfter = (int)$pdo->query("SELECT COUNT(*) FROM users WHERE email = '$dupEmail'")->fetchColumn();

    $tc5Passed = ($tc5Res['success'] === false)
        && ($tc5Res['message'] === 'Email address is already registered.')
        && ($countWithEmailBefore === 1)
        && ($countWithEmailAfter === 1);

    $results[] = [
        'id'       => 5,
        'name'     => 'Duplicate Email Validation',
        'input'    => "Email: '$dupEmail' (Attempting re-registration with duplicate email)",
        'expected' => 'Email address is already registered. (Original record preserved, count = 1)',
        'actual'   => "{$tc5Res['message']} (Existing email count preserved at: $countWithEmailAfter)",
        'status'   => $tc5Passed ? 'PASS' : 'FAIL',
        'details'  => 'Verified uniqueness check & MySQL UNIQUE constraint prevent duplicate email.'
    ];

    // -------------------------------------------------------------
    // Test Case 6: Duplicate Username Validation
    // -------------------------------------------------------------
    $dupUsername = 'duplicate_uname_test';
    runTestRegistration($pdo, [
        'full_name'        => 'First Username Owner',
        'username'         => $dupUsername,
        'email'            => 'first_' . bin2hex(random_bytes(2)) . '@testsuite.local',
        'password'         => 'InitialPass123!',
        'confirm_password' => 'InitialPass123!'
    ]);

